use sq17challenge;


-- 1.Calculate the total sales value from non-cancelled orders.
SELECT 
    SUM(oi.quantity * oi.unit_price) AS total_sales_value
FROM orders o
JOIN order_items oi ON o.order_id = oi.order_id
WHERE o.order_status != 'Cancelled';





-- 2.Identify which product categories generate the most sales.

SELECT 
    p.category, 
    SUM(oi.quantity * oi.unit_price) AS total_sales
FROM products p
JOIN order_items oi ON p.product_id = oi.product_id
JOIN orders o ON oi.order_id = o.order_id
WHERE o.status != 'Cancelled'
GROUP BY p.category
ORDER BY total_sales DESC;



-- 3.Find the 10 products generating the most sales value.



SELECT 
    p.product_id, 
    p.product_name, 
    SUM(oi.quantity * oi.unit_price) AS total_sales_value
FROM products p
JOIN order_items oi ON p.product_id = oi.product_id
JOIN orders o ON oi.order_id = o.order_id
WHERE o.status != 'Cancelled'
GROUP BY p.product_id, p.product_name
ORDER BY total_sales_value DESC
LIMIT 10;



-- 4.Calculate the total quantity sold for each product.



SELECT 
    p.product_id, 
    p.product_name, 
    SUM(oi.quantity) AS total_quantity_sold
  FROM products p
JOIN order_items oi ON p.product_id = oi.product_id
JOIN orders o ON oi.order_id = o.order_id
WHERE o.status != 'Cancelled'
GROUP BY p.product_id, p.product_name
ORDER BY total_quantity_sold DESC;




-- 5.Calculate the average product selling price in each category.

SELECT 
    category, 
    AVG(price) AS avg_selling_price
FROM products
GROUP BY category
ORDER BY avg_selling_price DESC;






-- 6.Calculate sales value generated by each sales channel.




SELECT 
    o.sales_channel, 
    SUM(oi.quantity * oi.unit_price) AS total_sales_value
FROM orders o
JOIN order_items oi ON o.order_id = oi.order_id
WHERE o.status != 'Cancelled'
GROUP BY o.sales_channel
ORDER BY total_sales_value DESC;






-- 7. calculate estimated profit by product using the product cost and item selling price.


SELECT 
    p.product_id, 
    p.product_name, 
    SUM(oi.quantity * (oi.unit_price - p.cost)) AS total_estimated_profit
FROM products p
JOIN order_items oi ON p.product_id = oi.product_id
JOIN orders o ON oi.order_id = o.order_id
WHERE o.status != 'Cancelled'
GROUP BY p.product_id, p.product_name
ORDER BY total_estimated_profit DESC;








-- 8.Find the five categories with the highest total quantity sold.

SELECT 
    p.category, 
    SUM(oi.quantity) AS total_quantity_sold
FROM products p
JOIN order_items oi ON p.product_id = oi.product_id
JOIN orders o ON oi.order_id = o.order_id
WHERE o.status != 'Cancelled'
GROUP BY p.category
ORDER BY total_quantity_sold DESC
LIMIT 5;
